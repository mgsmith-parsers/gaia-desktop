package tools.pantheum.gaia.desktop;

import tools.pantheum.gaia.GaiaConstants;
import tools.pantheum.gaia.GaiaVersion;
import tools.pantheum.gaia.desktop.parse.Languages;
import tools.pantheum.gaia.desktop.ui.MainView;
import javafx.application.Application;
import javafx.scene.Scene;
import javafx.scene.image.Image;
import javafx.stage.Stage;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * GAIA-Desktop entry point.
 *
 * <p>A JavaFX front-end over the GAIA GS1 parser ({@link tools.pantheum.gaia.GaiaParser}):
 * type, paste, open, or scan an input, and read the result as the same instrument-readout
 * HTML report the demo module writes to disk — rendered live in a {@code WebView} instead.
 * Scanner input comes from the JavaPOS control wired up in
 * {@link tools.pantheum.gaia.desktop.scanner.ScannerService}, the same SNAPI-over-USB-HID
 * path the CLI scanner front-end uses.
 *
 * <p>Run it:
 * <pre>
 *   mvn javafx:run                        # development — JavaFX on the module path
 *   java -jar target/gaia-desktop.jar     # packaged jar, with target/lib/ beside it
 *   java -jar target/gaia-desktop.jar --language=FR
 * </pre>
 *
 * <p>{@code --language} opens the window in that language <b>for this run only</b> — see
 * {@link #languageOverride()}.
 *
 * <p>The packaged jar runs through {@link Launcher} in either packaging: by default it carries
 * only this module's classes and names its dependencies on the manifest {@code Class-Path},
 * and {@code -Pfat} builds the self-contained one instead.
 */
public class GaiaDesktopApp extends Application {

    private static final Logger log = LoggerFactory.getLogger(GaiaDesktopApp.class);

    private static final String STYLESHEET = "/css/gaia-desktop.css";

    private MainView view;

    public static void main(String[] args) {
        launch(args);
    }

    @Override
    public void start(Stage stage) {
        // Both versions in the first log line: it is the line a bug report gets pasted from.
        log.info("GAIA Desktop v{} starting (built {}, GAIA Parser v{})",
                GaiaDesktopVersion.VERSION, GaiaDesktopVersion.TIMESTAMP, GaiaVersion.VERSION);

        view = new MainView(languageOverride());
        view.setHostServices(getHostServices());

        Scene scene = new Scene(view, 1280, 820);
        var css = GaiaDesktopApp.class.getResource(STYLESHEET);
        if (css != null) {
            scene.getStylesheets().add(css.toExternalForm());
        } else {
            log.warn("Stylesheet {} not found on the classpath — falling back to the default look", STYLESHEET);
        }

        // The product name, not a sentence — it needs no translating and no version suffix.
        stage.setTitle("GAIA Desktop");
        addWindowIcons(stage);
        stage.setScene(scene);
        stage.setMinWidth(900);
        stage.setMinHeight(600);
        stage.show();
    }

    /** The window icon at each size, smallest first; generated by tools/icon/GaiaIcon.java. */
    private static final int[] ICON_SIZES = {16, 32, 64, 128, 256};

    /**
     * Gives the window the app's icon — the title bar and taskbar on Windows and Linux. macOS
     * ignores window icons and shows the app bundle's (GAIA Desktop.app's .icns) in the Dock.
     * A missing size is skipped rather than fatal: an icon is not worth failing to start over.
     */
    private static void addWindowIcons(Stage stage) {
        for (int size : ICON_SIZES) {
            var url = GaiaDesktopApp.class.getResource("/icons/gaia-desktop-" + size + ".png");
            if (url != null) stage.getIcons().add(new Image(url.toExternalForm()));
        }
    }

    /**
     * The language named by {@code --language=…}, or {@code null} when the argument is absent
     * or unusable.
     *
     * <p>The override lasts for the run and is <b>not</b> written back: a launcher shortcut, a
     * demo, or a kiosk profile can open the app in one language without quietly rewriting the
     * user's saved setting. Changing the language inside the app is still a real choice and is
     * still saved.
     *
     * <p>A value that names no catalogue is logged and ignored rather than fatal — refusing to
     * start over a typo in a shortcut would be the worse failure.
     */
    private GaiaConstants.Language languageOverride() {
        Parameters parameters = getParameters();
        String value = parameters == null ? null : parameters.getNamed().get("language");
        if (value == null || value.trim().isEmpty()) return null;

        GaiaConstants.Language language = Languages.fromArgument(value);
        if (language == null) {
            log.warn("Ignoring --language={} — no catalogue by that name. Accepted codes: {}",
                    value, Languages.acceptedCodes());
            return null;
        }
        log.info("--language={} → {} (this run only; the saved setting is untouched)", value, language);
        return language;
    }

    @Override
    public void stop() {
        // Release the JavaPOS device; a claimed scanner stays claimed until the process
        // exits otherwise, and the next run cannot claim it.
        if (view != null) view.shutdown();
        log.info("GAIA-Desktop stopped");
    }
}
